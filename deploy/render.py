"""Render the runtime config for one MODE, from deploy/liquor.env.

    python3 deploy/render.py            # writes deploy/runtime/*
    python3 deploy/render.py --wait     # blocks until every camera stream is up

MediaMTX is the only thing that talks to cameras. In both modes it serves
each camera as rtsp://127.0.0.1:8554/<camera_id> (the AI reads it) and as HLS
on 127.0.0.1:8888/<camera_id>/ (the dashboard's live view, through Caddy):

  MODE=test        every camera replays its playlist video from the store
                   manifest, looped forever -- the same footage the demo uses,
                   normalised to H.264 by ai/tools/rtsp_sim.py
  MODE=production  every camera is relayed from its real RTSP address in
                   deploy/cameras.production.json

So the AI manifest written here is identical in both modes: only where
MediaMTX gets each stream from changes. MediaMTX also records every stream
for a few minutes, so evidence clips are cut at the camera's native frame
rate (ai/src/infra/recorded_clips.py).

Outputs (deploy/runtime/, regenerated on every start, never edited by hand):
  mediamtx.yml       the camera gateway
  ai_manifest.json   the store manifest with every camera pointed at MediaMTX
  Caddyfile          web front: dashboard, /api -> Go, /live -> MediaMTX HLS
"""
from __future__ import annotations

import argparse
import base64
import json
import os
import shlex
import subprocess
import sys
import time
from pathlib import Path

DEPLOY = Path(__file__).resolve().parent
ROOT = DEPLOY.parent
RUNTIME = DEPLOY / "runtime"
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "ai" / "tools"))

RTSP_PORT = 8554
HLS_PORT = 8888
PLAYBACK_PORT = 9996
API_PORT = 3000


def load_env(path: Path) -> dict[str, str]:
    env = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        env[key.strip()] = value
    # The process environment wins, as everywhere else in this project.
    return {key: os.environ.get(key, value) for key, value in env.items()}


def settings() -> dict[str, str]:
    path = DEPLOY / "liquor.env"
    if not path.exists():
        sys.exit(f"{path} is missing: copy deploy/liquor.env.example and fill it in")
    env = load_env(path)
    mode = env.get("MODE", "")
    if mode not in ("test", "production"):
        sys.exit(f"MODE must be test or production, got {mode!r}")
    for key in ("STORE_MANIFEST", "WEB_LISTEN", "PUBLIC_URL", "MEDIAMTX_READ_USER", "MEDIAMTX_READ_PASS"):
        if not env.get(key):
            sys.exit(f"{key} is required in deploy/liquor.env")
    return env


def manifest_path(env) -> Path:
    path = Path(env["STORE_MANIFEST"])
    return path if path.is_absolute() else ROOT / path


def camera_ids(manifest: Path) -> list[str]:
    return [camera["camera_id"] for camera in json.loads(manifest.read_text())["cameras"]]


def production_sources(ids: list[str]) -> dict[str, dict]:
    path = DEPLOY / "cameras.production.json"
    if not path.exists():
        sys.exit(f"MODE=production needs {path} (see cameras.production.example.json)")
    sources = json.loads(path.read_text())
    missing = [camera_id for camera_id in ids if camera_id not in sources]
    if missing:
        sys.exit(f"cameras.production.json has no source for {missing}")
    return sources


def mediamtx_config(env, ids: list[str]) -> str:
    user, password = env["MEDIAMTX_READ_USER"], env["MEDIAMTX_READ_PASS"]
    record_dir = RUNTIME / "recordings"
    lines = [
        "# Generated by deploy/render.py -- do not edit by hand.",
        f"# MODE={env['MODE']}",
        "logLevel: info",
        "readTimeout: 30s",
        "writeTimeout: 30s",
        "",
        "# Everything listens on loopback: the AI and Caddy are on this host, and",
        "# browsers only ever reach HLS through Caddy's /live/ (checked by the API).",
        "rtspTransports: [tcp]",
        f"rtspAddress: 127.0.0.1:{RTSP_PORT}",
        "rtmp: no",
        "srt: no",
        "webrtc: no",
        "api: no",
        "hls: yes",
        f"hlsAddress: 127.0.0.1:{HLS_PORT}",
        "hlsVariant: mpegts",
        "hlsSegmentDuration: 1s",
        "hlsSegmentCount: 4",
        "",
        "# Recordings let the AI cut evidence clips at the camera's own frame rate.",
        "playback: yes",
        f"playbackAddress: 127.0.0.1:{PLAYBACK_PORT}",
        "",
        "# Publishers (test mode's ffmpeg, production transcoders) are local and",
        "# anonymous; reading needs the read user, as a real camera would.",
        "authInternalUsers:",
        "  - user: any",
        "    ips: ['127.0.0.1/32', '::1/128']",
        "    permissions:",
        "      - action: publish",
        "      - action: playback",
        f"  - user: {user}",
        f"    pass: {password}",
        "    permissions:",
        "      - action: read",
        "",
        "pathDefaults:",
        "  record: yes",
        f"  recordPath: {record_dir}/%path/%Y-%m-%d_%H-%M-%S-%f",
        "  recordFormat: fmp4",
        "  recordPartDuration: 1s",
        "  recordSegmentDuration: 60s",
        "  recordDeleteAfter: 10m",
        "",
        "paths:",
    ]
    publish = "rtsp://127.0.0.1:$RTSP_PORT/$MTX_PATH"
    if env["MODE"] == "test":
        import rtsp_sim

        work = Path(env.get("PLAYLIST_CACHE") or RUNTIME / "playlists")
        for camera_id, video in rtsp_sim.load_cameras(manifest_path(env)):
            # Always through the normaliser: one H.264 cycle per camera, which
            # MediaMTX can record and every browser can play as HLS.
            playlist = video if isinstance(video, list) else [(video, 1)]
            concat = rtsp_sim.prepare_playlist(camera_id, playlist, work)
            cmd = ("ffmpeg -hide_banner -loglevel warning -re -stream_loop -1 -fflags +genpts "
                   f"-f concat -safe 0 -i {shlex.quote(str(concat))} -c copy -f rtsp -rtsp_transport tcp {publish}")
            lines += [f"  {camera_id}:", f"    runOnInit: {cmd}", "    runOnInitRestart: yes"]
    else:
        for camera_id, source in production_sources(ids).items():
            if camera_id not in ids:
                continue
            url = source["url"]
            transcode = source.get("transcode")
            if not transcode:
                # Relayed as-is: one connection to the camera, shared by the AI,
                # the recorder and every viewer. Needs H.264 for HLS/recording.
                lines += [f"  {camera_id}:", f"    source: {json.dumps(url)}",
                          "    rtspTransport: tcp", "    sourceOnDemand: no"]
                continue
            # HEVC cameras: re-encoded once to H.264 (NVENC on the GPU, or CPU).
            codec = {"nvenc": "h264_nvenc -preset p4 -tune ll", "cpu": "libx264 -preset veryfast -tune zerolatency"}[transcode]
            cmd = ("ffmpeg -hide_banner -loglevel warning -rtsp_transport tcp "
                   f"-i {shlex.quote(url)} -an -c:v {codec} -g 30 -bf 0 -f rtsp -rtsp_transport tcp {publish}")
            lines += [f"  {camera_id}:", f"    runOnInit: {cmd}", "    runOnInitRestart: yes"]
    return "\n".join(lines) + "\n"


def write_ai_manifest(env, ids: list[str]) -> Path:
    import rtsp_sim

    dest = RUNTIME / "ai_manifest.json"
    rtsp_sim.write_rtsp_manifest(
        manifest_path(env), dest, [(camera_id, None) for camera_id in ids],
        host="127.0.0.1", port=RTSP_PORT, user=env["MEDIAMTX_READ_USER"], password=env["MEDIAMTX_READ_PASS"],
        forever=True, playback_url=f"http://127.0.0.1:{PLAYBACK_PORT}")
    return dest


def security_headers() -> list[tuple[str, str]]:
    """The dashboard's headers, from the same file Cloudflare Pages used."""
    headers_file = ROOT / "frontend" / "dist" / "_headers"
    if not headers_file.exists():
        headers_file = ROOT / "frontend" / "public" / "_headers"
    out = []
    for line in headers_file.read_text().splitlines():
        if line.startswith((" ", "\t")) and ":" in line:
            name, _, value = line.strip().partition(":")
            out.append((name.strip(), value.strip()))
    return out


def caddyfile(env) -> str:
    listen = env["WEB_LISTEN"]
    https = bool(env.get("SITE_ADDRESS"))
    host, _, port = listen.rpartition(":")
    # Plain HTTP answers any Host on the bound address (localhost through an
    # SSH tunnel, the server's IP...); a domain gets automatic HTTPS.
    site = env["SITE_ADDRESS"] if https else f"http://:{port}"
    bind = "" if https else f"\n\tbind {host}"
    basic = base64.b64encode(f"{env['MEDIAMTX_READ_USER']}:{env['MEDIAMTX_READ_PASS']}".encode()).decode()
    dist = ROOT / "frontend" / "dist"
    headers = []
    for name, value in security_headers():
        if not https:
            # Over plain HTTP these would send the browser to https:// and break it.
            if name.lower() == "strict-transport-security":
                continue
            if name.lower() == "content-security-policy":
                value = "; ".join(part for part in value.split("; ") if part.strip() != "upgrade-insecure-requests")
        headers.append((name, value))
    header_lines = "\n".join(f'\t\t\t{name} "{value}"' for name, value in headers)
    return f"""# Generated by deploy/render.py -- do not edit by hand.
{{
\tadmin off
\tpersist_config off
}}

{site} {{{bind}
\tencode zstd gzip

\t# The Go API. It sees the browser's address through X-Forwarded-For
\t# (TRUST_PROXY with 127.0.0.1 as the trusted proxy).
\thandle /api/* {{
\t\treverse_proxy 127.0.0.1:{API_PORT}
\t}}

\t# Live view: every playlist and segment request is first checked by the
\t# API (the liquor_live cookie must allow this camera), then served by
\t# MediaMTX's HLS on loopback with the read user's credentials.
\t# `route` keeps this order: the check must see the original /live/... path.
\thandle /live/* {{
\t\troute {{
\t\t\tforward_auth 127.0.0.1:{API_PORT} {{
\t\t\t\turi /api/v1/live/authorize
\t\t\t}}
\t\t\turi strip_prefix /live
\t\t\t# MediaMTX otherwise first redirects a request without cookies to
\t\t\t# ?cookieCheck=1 (to learn whether the browser keeps cookies). Its
\t\t\t# auth here is the Authorization header, so that probe is skipped.
\t\t\turi query cookieCheck 1
\t\t\theader Cache-Control "no-store"
\t\t\treverse_proxy 127.0.0.1:{HLS_PORT} {{
\t\t\t\theader_up Authorization "Basic {basic}"
\t\t\t\theader_up -Cookie
\t\t\t\t# Any redirect MediaMTX still sends stays under /live/.
\t\t\t\theader_down Location ^/ /live/
\t\t\t}}
\t\t}}
\t}}

\t# The dashboard (frontend/dist): landing page, public demo, owner login.
\thandle {{
\t\theader {{
{header_lines}
\t\t}}
\t\troot * {dist}
\t\ttry_files {{path}} /index.html
\t\tfile_server
\t}}
}}
"""


def wait_for_streams(env, timeout: float) -> None:
    ids = camera_ids(manifest_path(env))
    deadline = time.time() + timeout
    pending = list(ids)
    while pending and time.time() < deadline:
        still = []
        for camera_id in pending:
            url = f"rtsp://{env['MEDIAMTX_READ_USER']}:{env['MEDIAMTX_READ_PASS']}@127.0.0.1:{RTSP_PORT}/{camera_id}"
            probe = subprocess.run(["ffprobe", "-v", "error", "-rtsp_transport", "tcp", "-select_streams", "v:0",
                                    "-show_entries", "stream=codec_name", "-of", "csv=p=0", url],
                                   capture_output=True, text=True, timeout=30)
            if probe.returncode != 0 or not probe.stdout.strip():
                still.append(camera_id)
        pending = still
        if pending:
            print(f"waiting for {len(pending)} stream(s): {', '.join(pending)}", flush=True)
            time.sleep(5)
    if pending:
        sys.exit(f"streams not up after {timeout:.0f}s: {pending}")
    print(f"all {len(ids)} camera streams are up", flush=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--wait", action="store_true", help="wait until every camera stream is readable")
    parser.add_argument("--caddy", action="store_true",
                        help="write only the Caddyfile (the web front must not redo the camera config)")
    parser.add_argument("--timeout", type=float, default=900)
    args = parser.parse_args()
    env = settings()
    if args.wait:
        wait_for_streams(env, args.timeout)
        return
    RUNTIME.mkdir(parents=True, exist_ok=True)
    caddy = RUNTIME / "Caddyfile"
    caddy.write_text(caddyfile(env))
    caddy.chmod(0o600)
    if args.caddy:
        return
    ids = camera_ids(manifest_path(env))
    config = RUNTIME / "mediamtx.yml"
    config.write_text(mediamtx_config(env, ids))
    config.chmod(0o600)  # holds the read password (and, in production, camera addresses)
    manifest = write_ai_manifest(env, ids)
    manifest.chmod(0o600)
    print(f"MODE={env['MODE']}: {len(ids)} cameras -> {config.relative_to(ROOT)}, "
          f"{manifest.relative_to(ROOT)}, {caddy.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
