package security

import "testing"

func TestPasswordRoundTrip(t *testing.T) {
	hash, err := HashPassword("a-long-test-password")
	if err != nil {
		t.Fatalf("HashPassword() error = %v", err)
	}
	valid, err := VerifyPassword("a-long-test-password", hash)
	if err != nil {
		t.Fatalf("VerifyPassword() error = %v", err)
	}
	if !valid {
		t.Fatal("VerifyPassword() = false, want true")
	}
	invalid, err := VerifyPassword("different-password", hash)
	if err != nil {
		t.Fatalf("VerifyPassword(wrong) error = %v", err)
	}
	if invalid {
		t.Fatal("VerifyPassword(wrong) = true, want false")
	}
}

func TestVerifyPasswordAcceptsLegacyNodeArgon2Hash(t *testing.T) {
	const legacyHash = "$argon2id$v=19$m=65536,p=4,t=3$tRJklxOdZO9aABYGMhSuPQ$efdf+S6xCWV0Qd61ZJlhMSYxZUR4weZFzfXrlb2FE9A"

	valid, err := VerifyPassword("nest-go-compatibility-password", legacyHash)
	if err != nil {
		t.Fatalf("VerifyPassword() error = %v", err)
	}
	if !valid {
		t.Fatal("VerifyPassword() rejected a valid hash produced by the legacy Node argon2 package")
	}
}

// Owner accounts seeded by the AI service before logins moved here were
// hashed with Python's bcrypt ($2b$, cost 12). They must still log in.
func TestVerifyPasswordAcceptsPythonBcryptHash(t *testing.T) {
	// Generated by Python's bcrypt (the library seed_cloud_store.py used):
	//   bcrypt.hashpw(b"owner-test-password", bcrypt.gensalt(12))
	const pythonHash = "$2b$12$.eIq6CAh0NqzujQGWMSJWu2gLykf4iJ3l4ZM1eyTcCHe0uM49yMKu"
	if !IsLegacyHash(pythonHash) {
		t.Fatal("IsLegacyHash() = false for a $2b$ hash")
	}
	valid, err := VerifyPassword("owner-test-password", pythonHash)
	if err != nil || !valid {
		t.Fatalf("VerifyPassword(right) = %v, %v; want true, nil", valid, err)
	}
	valid, err = VerifyPassword("wrong-password", pythonHash)
	if err != nil || valid {
		t.Fatalf("VerifyPassword(wrong) = %v, %v; want false, nil", valid, err)
	}
	if IsLegacyHash(mustHash(t, "x-long-password")) {
		t.Fatal("a fresh Argon2id hash was reported as legacy")
	}
}

func TestVerifyPasswordRejectsExpensiveBcrypt(t *testing.T) {
	// A well-formed hash at cost 31: verifying it would take hours.
	const tampered = "$2b$31$.eIq6CAh0NqzujQGWMSJWu2gLykf4iJ3l4ZM1eyTcCHe0uM49yMKu"
	if valid, err := VerifyPassword("owner-test-password", tampered); err == nil || valid {
		t.Fatalf("VerifyPassword() = %v, %v; want rejection", valid, err)
	}
}

func mustHash(t *testing.T, password string) string {
	t.Helper()
	hash, err := HashPassword(password)
	if err != nil {
		t.Fatal(err)
	}
	return hash
}
